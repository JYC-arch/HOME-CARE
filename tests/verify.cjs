const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const H = require('../activity.js');
const root = path.resolve(__dirname, '..');
const r = H.blank(1);
assert.equal(H.validate(JSON.parse(JSON.stringify(r))).group, 1);
assert.equal(H.errors(r).length, 13);
assert.equal(H.required.length, 11);
assert.equal(new Set(H.countries.map(c => c.id)).size, 7);
assert.notEqual(H.key(1), H.key(2));
assert.ok(H.validUrl('https://www.nhi.gov.tw/'));
assert.equal(H.validUrl('javascript:alert(1)'), false);
assert.equal(H.validUrl('data:text/html,test'), false);
assert.equal(H.validDate('2026-02-30'), false);
assert.equal(H.validDate('2024-02-29'), true);
H.required.forEach(f => { r.answers[f] = '測試內容：<script>不應執行</script>\n第二行'; });
r.sources = [{ name: '衛福部', url: 'https://www.mohw.gov.tw/', date: '2026-11-23', type: 'official' }];
r.status = 'complete';
assert.deepEqual(H.errors(r), []);
const restored = H.validate(JSON.parse(JSON.stringify(r)));
assert.equal(restored.status, 'complete');
assert.ok(H.toMarkdown(restored).includes('與台灣比較'));
assert.ok(H.toMarkdown(restored).includes('https://www.mohw.gov.tw/'));
assert.ok(H.toMarkdown(restored).includes('<script>不應執行</script>'));
const wrongGroup = {...r, group: 8};
assert.throws(() => H.validate(wrongGroup));
const incomplete = structuredClone(r); incomplete.answers.learn = '';
assert.throws(() => H.validate(incomplete));
const unsafeSource = structuredClone(r); unsafeSource.sources[0].url = 'javascript:alert(1)';
assert.throws(() => H.validate(unsafeSource));
const unfinished = H.blank(2); unfinished.sources[0].url = 'https://';
assert.equal(H.validate(unfinished).sources[0].url, 'https://', 'partial drafts must round-trip');
const noOfficial = structuredClone(r); noOfficial.sources[0].type = 'other';
assert.ok(H.errors(noOfficial).some(e => e.message.includes('官方')));
const oversize = structuredClone(r); oversize.answers.learn = '字'.repeat(3001);
assert.throws(() => H.validate(oversize));
const alien = {...r, schema: 'ltc-team-v1'};
assert.throws(() => H.validate(alien));
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const md = fs.readFileSync(path.join(root, 'README.md'), 'utf8');
for (const heading of ['六組班的調整', '## 時間安排', '## 全班對照表', '## 簡易評分規準']) assert.equal(md.includes(heading), false);
for (const asset of ['activity.js', 'app.js', 'style.css']) { assert.ok(html.includes(asset)); assert.ok(fs.existsSync(path.join(root, asset))); }
assert.equal(app.includes('innerHTML'), false, 'user answers must render as text');
for (const id of [...app.matchAll(/\$\('([^']+)'\)/g)].map(m => m[1])) {
  if (id.endsWith('-') || H.fields.includes(id) || id === 'source-') continue;
  assert.ok(html.includes('id="' + id + '"'), 'Missing HTML element ' + id);
}
console.log('Passed: drafts, completed results, required fields, official sources, safe URLs, dates, file validation, text export and removed sections.');
